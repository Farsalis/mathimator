_FORBIDDEN = ("begin_ambient_camera_rotation", "manimlib", "opengl")


def test_axes_function_expression_edit_keeps_durations() -> None:
    session = Session(empty_project())
    session.edit({"op": "add_axes_function"})
    scene = session.project.scene
    assert [item.type for item in scene.objects] == ["axes", "function_plot"]
    axes, plot = scene.objects
    assert plot.params["expression"] == "sin(x)"
    assert plot.params["color"] == "#58C4DD"
    assert axes.params["xRange"] == [-6.5, 6.5, 1]
    assert axes.params["yRange"] == [-1.5, 1.5, 0.5]
    assert axes.params["showLabels"] is True
    assert [beat.action for beat in scene.beats] == ["create", "create"]
    assert [beat.duration for beat in scene.beats] == [2, 2]
    session.edit({"op": "set_beat_duration", "beatId": "beat_2", "duration": 3})
    session.edit({"op": "set_expression", "objectId": "plot_1", "expression": "cos(x)"})
    assert session.project.scene.objects[1].params["expression"] == "cos(x)"
    assert [beat.duration for beat in session.project.scene.beats] == [2, 3]
    assert "lambda x: np.cos(x)" in generate(session.project)


def test_formula_transform_inserts_the_section_4_defaults() -> None:
    session = Session(empty_project())
    session.edit({"op": "add_formula_transform"})
    scene = session.project.scene
    assert scene.kind == "scene"
    assert [item.type for item in scene.objects] == ["math_formula", "math_formula"]
    source, dest = scene.objects
    assert source.params["latex"] == r"y = \sin(x)"
    assert dest.params["latex"] == r"y = \cos(x)"
    assert source.params["anchor"] == "edge_up"
    assert dest.params["anchor"] == "edge_up"
    assert source.params["color"] == "#FFFFFF"
    assert dest.params["color"] == "#FFFFFF"
    assert [beat.action for beat in scene.beats] == ["write", "transform_formula"]
    assert [beat.duration for beat in scene.beats] == [2, 2]
    assert scene.beats[0].targets == [source.id]
    assert scene.beats[1].targets == [source.id, dest.id]
    assert scene.template_instances[0].template_id == "formula_transform"
    generated = generate(session.project)
    assert "TransformMatchingTex(formula_1, formula_2)" in generated
    assert "Write(formula_1)" in generated
    assert "MathTex" in generated
    assert "Create(" not in generated
    session.edit({"op": "set_latex", "objectId": "formula_2", "latex": r"y = \cos(2x)"})
    revised = generate(session.project)
    assert r"y = \cos(2x)" in revised
    assert "TransformMatchingTex(formula_1, formula_2)" in revised
    assert [beat.duration for beat in session.project.scene.beats] == [2, 2]


def test_three_d_surface_and_curve_match_section_5() -> None:
    session = Session(empty_project())
    session.edit({"op": "add_three_d_axes"})
    scene = session.project.scene
    assert scene.kind == "three_d_scene"
    assert scene.camera is not None
    assert (scene.camera.phi, scene.camera.theta, scene.camera.zoom) == (65, -45, 1)
    assert [item.type for item in scene.objects] == ["three_d_axes", "surface"]
    axes, surface = scene.objects
    assert axes.params["xRange"] == [-3, 3, 1]
    assert axes.params["yRange"] == [-3, 3, 1]
    assert axes.params["zRange"] == [-2, 2, 1]
    assert surface.params["expression"] == "sin(x)*cos(y)"
    assert surface.params["uRange"] == [-2.5, 2.5]
    assert surface.params["vRange"] == [-2.5, 2.5]
    assert surface.params["resolution"] == [8, 8]
    assert surface.params["color"] == "#58C4DD"
    assert [beat.action for beat in scene.beats] == ["create", "create"]
    assert [beat.duration for beat in scene.beats] == [2, 2]
    assert scene.beats[0].targets == [axes.id]
    assert scene.beats[1].targets == [surface.id]
    surface_source = generate(session.project)
    assert surface_source == SURFACE_SOURCE
    for token in _FORBIDDEN:
        assert token not in surface_source

    beat_ids = [beat.id for beat in scene.beats]
    session.edit({"op": "set_three_d_mode", "mode": "curve"})
    switched = session.project.scene
    assert [beat.id for beat in switched.beats] == beat_ids
    assert switched.beats[1].action == "create"
    assert switched.beats[1].duration == 2
    assert switched.objects[1].type == "parametric_curve"
    assert switched.objects[1].id == "curve_1"
    assert switched.beats[1].targets == ["curve_1"]
    assert switched.objects[1].params["components"] == ["cos(t)", "sin(t)", "t / 3"]
    assert switched.objects[1].params["tRange"] == [0, 12.56]
    assert switched.objects[1].params["color"] == "#F2CC8F"
    curve_source = generate(session.project)
    assert curve_source == CURVE_SOURCE
    for token in _FORBIDDEN:
        assert token not in curve_source

    session.edit({"op": "set_three_d_mode", "mode": "surface"})
    assert [beat.id for beat in session.project.scene.beats] == beat_ids
    assert session.project.scene.objects[1].id == "surface_1"
    assert generate(session.project) == SURFACE_SOURCE


