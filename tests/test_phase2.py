def _starts(project: Project) -> list[float]:
    return derived_starts([beat.duration for beat in project.scene.beats])


def _fenced(spec: str, heading: str, language: str) -> str:
    start = spec.index(heading)
    fence = f"```{language}\n"
    begin = spec.index(fence, start) + len(fence)
    end = spec.index("```", begin)
    return spec[begin:end]


def _manim_frame_counts(source: str, fps: int) -> list[int]:
    """The frames each beat of ``source`` draws at ``fps``, by the rules of Manim 0.22.

    A play draws ``len(np.arange(0, run_time, 1 / fps))`` frames (``Scene.get_time_progression``)
    and a static wait ``int(seconds / (1 / fps))`` (``CairoRenderer.freeze_current_frame``).
    """
    module = ast.parse(source)
    namespace: dict[str, object] = {"config": SimpleNamespace(frame_rate=fps)}
    helpers = [node for node in module.body if isinstance(node, ast.FunctionDef)]
    exec(compile(ast.Module(body=helpers, type_ignores=[]), "scene.py", "exec"), namespace)
    construct = next(
        node for node in ast.walk(module) if isinstance(node, ast.FunctionDef) and node.name == "construct"
    )
    step = 1 / fps
    counts: list[int] = []
    for statement in construct.body:
        call = statement.value if isinstance(statement, ast.Expr) else None
        if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Attribute):
            continue
        if call.func.attr == "wait":
            counts.append(int(_evaluate(call.args[0], namespace) / step))
        elif call.func.attr == "play":
            run_time = _evaluate(next(item.value for item in call.keywords if item.arg == "run_time"), namespace)
            # A shorter play makes Manim warn and stretch it to one frame.
            assert run_time >= step
            counts.append(len(np.arange(0, run_time, step)))
    return counts


def _evaluate(node: ast.expr, namespace: dict[str, object]) -> float:
    return float(eval(compile(ast.Expression(body=node), "scene.py", "eval"), namespace))


def _ready(client: SupervisorClient) -> None:
    client.send({"cmd": "status", "id": "status"})
    client.wait_for(lambda event: event.get("event") == "ready" and event.get("jobId") == "status", 10)


def _argv_count(log_path: Path) -> int:
    if not log_path.is_file():
        return 0
    return log_path.read_text(encoding="utf-8", errors="replace").count("argv: ")


def _wait_manim(log_path: Path) -> int:
    """The pid of the first Manim the supervisor starts."""
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        started = manim_pids(log_path)
        if started:
            return started[0]
        time.sleep(0.02)
    raise AssertionError("fake manim did not start")


def _end(client: SupervisorClient, job_id: str) -> None:
    """Cancel the job and wait for its last line, so closing the worker leaves no fake Manim behind (F028)."""
    client.send({"cmd": "cancel", "id": f"cancel-{job_id}", "jobId": job_id})
    client.wait_for(lambda event: event.get("jobId") == job_id and event.get("event") in {"done", "error"}, 10)
