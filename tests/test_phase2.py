def test_journey_a_json_and_codegen_match_the_spec() -> None:
    spec = SPEC.read_text(encoding="utf-8")
    raw = _fenced(spec, "### Journey A document", "json")
    expected = _fenced(spec, "### Journey A, normative output", "python")
    assert JOURNEY.read_text(encoding="utf-8") == raw
    project = load_text(raw)
    assert dumps_project(project) == raw
    assert dumps_project(load_text(dumps_project(project))) == raw
    source = generate(project)
    assert source == expected
    assert source.startswith("# Generated by Mathimator. generatorVersion 1. manim==0.22.0\n")
    assert "MathTex" in source
    assert "Typst" not in source
    for token in ("fps", "854", "1920", "1080", "480"):
        assert token not in source


