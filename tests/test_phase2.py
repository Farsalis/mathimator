@pytest.mark.process_table
def test_preview_waits_behind_export_and_edits_do_not_cancel_it(tmp_path: Path) -> None:
    project = tmp_path / "queue-project"
    log_path = tmp_path / "queue.log"
    fake = write_fake_interpreter(tmp_path / "fake-manim.py", 1.2)
    client = start_supervisor(project, log_path, python=fake, init=True)
    try:
        _ready(client)
        client.send({"cmd": "export", "id": "export-1"})
        first = read_argv(log_path, timeout=10)
        assert first[1:4] == ["-m", "manim", "render"]
        client.send({"cmd": "render_preview", "id": "preview-wait"})
        client.send({"cmd": "edit", "id": "rename", "edit": {"op": "set_project_name", "name": "During export"}})
        renamed = client.wait_for(lambda event: event.get("jobId") == "rename", 10)
        assert renamed["event"] == "state"
        time.sleep(0.3)
        assert _argv_count(log_path) == 1
        assert _fake_pids(client.proc.pid, str(fake))
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline and _argv_count(log_path) < 2:
            time.sleep(0.05)
        assert _argv_count(log_path) == 2
    finally:
        client.close()


@pytest.mark.process_table
def test_a_new_preview_cancels_the_in_flight_preview(tmp_path: Path) -> None:
    project = tmp_path / "cancel-preview"
    log_path = tmp_path / "cancel-preview.log"
    fake = write_fake_interpreter(tmp_path / "fake-manim.py", 30)
    client = start_supervisor(project, log_path, python=fake, init=True)
    try:
        _ready(client)
        client.send({"cmd": "render_preview", "id": "preview-1"})
        read_argv(log_path, timeout=10)
        first = _wait_fake(client.proc.pid, fake)
        started = time.perf_counter()
        client.send({"cmd": "render_preview", "id": "preview-2"})
        deadline = started + 1.0
        while time.perf_counter() < deadline:
            if not process_alive(first):
                break
            time.sleep(0.01)
        assert not process_alive(first)
        assert time.perf_counter() - started < 1.0
    finally:
        client.close()


