def test_lesson_60_invalidation_from_disk() -> None:
    original = LESSON.read_text(encoding="utf-8")
    project = load_text(original)
    assert [beat.duration for beat in project.scene.beats] == [8, 8, 6, 8, 8, 8, 8, 6]

    eq_2_flags, before, after = _edit_lesson({"op": "set_latex", "objectId": "eq_2", "latex": r"y = \cos(2x)"})
    assert eq_2_flags == [False, False, False, False, False, False, True, True]
    marker = "self.play(Write(eq_1), run_time=6)\n"
    assert before.split(marker)[0] == after.split(marker)[0]
    assert r"y = \cos(2x)" in after
    assert r"y = \cos(x)" in before

    eq_1_flags, _before, after = _edit_lesson({"op": "set_latex", "objectId": "eq_1", "latex": r"y = \sin(2x)"})
    assert eq_1_flags == [False, False] + [True] * 6
    assert r"y = \sin(2x)" in after

    axes_flags, _before, after = _edit_lesson(
        {"op": "set_axes_range", "objectId": "axes_1", "axis": "x", "value": [-6, 6, 1]}
    )
    assert axes_flags == [True] * 8
    assert "x_range=[-6, 6, 1]" in after


def test_derived_starts_and_refused_documents(tmp_path: Path) -> None:
    reference = load_text(REFERENCE.read_text(encoding="utf-8"))
    starts = _starts(reference)
    assert starts == [0.0, 8.0, 18.0, 24.0, 28.0, 36.0, 44.0, 52.0]
    assert sum(float(beat.duration) for beat in reference.scene.beats) == 60.0

    raw = json.loads(JOURNEY.read_text(encoding="utf-8"))
    raw["scene"]["beats"][0]["start"] = 0
    with pytest.raises(DocumentError, match="start"):
        load_text(json.dumps(raw))

    versioned = json.loads(JOURNEY.read_text(encoding="utf-8"))
    versioned["schemaVersion"] = 2
    with pytest.raises(DocumentError, match="2"):
        load_text(json.dumps(versioned))

    missing = json.loads(JOURNEY.read_text(encoding="utf-8"))
    del missing["schemaVersion"]
    with pytest.raises(DocumentError, match="schemaVersion"):
        load_text(json.dumps(missing))

    unknown = json.loads(JOURNEY.read_text(encoding="utf-8"))
    unknown["extra"] = True
    with pytest.raises(DocumentError, match="extra"):
        load_text(json.dumps(unknown))

    nested = json.loads(JOURNEY.read_text(encoding="utf-8"))
    nested["scene"]["objects"][0]["params"]["tilt"] = 1
    with pytest.raises(DocumentError, match="tilt"):
        load_text(json.dumps(nested))

    destination = tmp_path / "project.json"
    project = load_text(JOURNEY.read_text(encoding="utf-8"))
    destination.write_text(dumps_project(project), encoding="utf-8", newline="\n")
    assert destination.read_bytes() == JOURNEY.read_bytes()
    again = destination.with_name("again.json")
    again.write_text(
        dumps_project(load_text(destination.read_text(encoding="utf-8"))),
        encoding="utf-8",
        newline="\n",
    )
    assert again.read_bytes() == destination.read_bytes()


def test_undo_redo_and_display_name() -> None:
    session = Session(load_text(REFERENCE.read_text(encoding="utf-8")))
    original = dumps_project(session.project)
    source = generate(session.project)
    session.mark_rendered("preview")
    session.edit({"op": "set_object_name", "objectId": "title_1", "name": "Heading"})
    session.edit({"op": "set_project_name", "name": "Renamed lesson"})
    assert generate(session.project) == source
    assert session.dirty_flags("preview") == [False] * 8
    saved = json.loads(dumps_project(session.project))
    assert saved["name"] == "Renamed lesson"
    assert "start" not in json.dumps(saved)
    assert "undo" not in saved

    fresh = Session(load_text(original))
    for index in range(50):
        fresh.edit(
            {
                "op": "set_beat_duration",
                "beatId": "beat_8",
                "duration": round(0.1 + index * 0.01, 3),
            }
        )
    fresh.undo()
    fresh.redo()
    for _ in range(50):
        fresh.undo()
    assert dumps_project(fresh.project) == original
    assert fresh.can_undo() is False
    reopened = Session(load_text(dumps_project(fresh.project)))
    assert reopened.can_undo() is False

    refused = Session(load_text(original))
    before = dumps_project(refused.project)
    with pytest.raises(DocumentError, match="0.1"):
        refused.edit({"op": "set_beat_duration", "beatId": "beat_8", "duration": 0.05})
    with pytest.raises(DocumentError, match="120"):
        refused.edit({"op": "set_beat_duration", "beatId": "beat_1", "duration": 80})
    assert dumps_project(refused.project) == before


def test_expression_grammar() -> None:
    variables = frozenset({"x"})
    assert expression_to_python("sin(x)", variables) == "np.sin(x)"
    assert expression_to_python("sin(x)^2", variables) == "np.sin(x) ** 2"
    assert expression_to_python("2*x + 1", variables) == "2 * x + 1"
    for rejected in ("np.sin(x)", "sin(x, 1)", "y", '__import__("os")'):
        with pytest.raises(DocumentError, match="This expression is not supported."):
            expression_to_python(rejected, variables)


def test_scrub_choice_does_not_describe_a_latency_budget(tmp_path: Path) -> None:
    """Pure file choice for 9.0 s. This is not a 100 ms UI measurement."""
    movie = tmp_path / "MainScene.mp4"
    movie.write_bytes(b"movie")
    partials = []
    beats = []
    starts = [0.0, 8.0, 18.0, 24.0, 28.0, 36.0, 44.0, 52.0]
    durations = [8.0, 10.0, 6.0, 4.0, 8.0, 8.0, 8.0, 8.0]
    for index, (start, duration) in enumerate(zip(starts, durations, strict=True)):
        path = tmp_path / f"partial-{index}.mp4"
        path.write_bytes(f"part-{index}".encode())
        partials.append(path)
        beats.append(
            IndexBeat(
                id=f"beat_{index + 1}",
                index=index,
                derived_start=start,
                duration=duration,
                partial=str(path),
                last_good=None,
                fresh=True,
            )
        )
    fresh = scrub_at(PreviewIndex(output=str(movie), beats=beats), 9.0)
    assert fresh["mode"] == "movie"
    assert fresh["time"] == 9.0
    assert fresh["beatIndex"] == 1
    assert fresh["badge"] is False

    beats[1].fresh = False
    beats[1].partial = None
    last_good = tmp_path / "last-good.mp4"
    last_good.write_bytes(b"previous")
    beats[1].last_good = str(last_good)
    dirty = scrub_at(PreviewIndex(output=str(movie), beats=beats), 9.0)
    assert dirty["mode"] == "partial"
    assert dirty["path"] == str(last_good)
    assert dirty["time"] == 1.0
    assert dirty["badge"] is True

    beats[1].last_good = None
    blank = scrub_at(PreviewIndex(output=str(movie), beats=beats), 9.0)
    assert blank["mode"] == "blank"
    assert blank["badge"] is True


@pytest.mark.process_table
def test_expression_rejection_does_not_spawn_manim(tmp_path: Path) -> None:
    project = tmp_path / "expr-project"
    log_path = tmp_path / "worker.log"
    client = start_supervisor(project, log_path, init=True)
    try:
        _ready(client)
        client.send({"cmd": "edit", "id": "add", "edit": {"op": "add_axes_function"}})
        added = client.wait_for(lambda event: event.get("jobId") == "add", 10)
        assert added["event"] == "state"
        client.send(
            {
                "cmd": "edit",
                "id": "bad",
                "edit": {
                    "op": "set_expression",
                    "objectId": "plot_1",
                    "expression": '__import__("os")',
                },
            }
        )
        rejected = client.wait_for(lambda event: event.get("jobId") == "bad", 10)
        assert rejected["event"] == "rejected"
        assert rejected["message"] == "This expression is not supported."
        assert client.proc.poll() is None
        assert _fake_pids(client.proc.pid, "manim") == []
    finally:
        client.close()
    log = log_path.read_text(encoding="utf-8")
    assert "argv:" not in log
    assert " -m manim" not in log


