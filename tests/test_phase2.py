def test_manim_draws_whole_seconds_exactly() -> None:
    """A whole second is a whole number of frames at every rate, so Manim draws an integer duration exactly."""
    for fps in (15, 30, 60):
        step = 1 / fps
        for seconds in range(1, 121):
            assert len(np.arange(0, seconds, step)) == seconds * fps
            assert int(seconds / step) == seconds * fps


