@pytest.mark.parametrize("fps", [15, 30, 60])
def test_every_beat_boundary_lands_on_the_nearest_frame(fps: int) -> None:
    """D63, G3.1, G3.3: frames counted the way Manim 0.22 draws them, at the preview and export rates."""
    raw = json.loads(JOURNEY.read_text(encoding="utf-8"))
    beats = raw["scene"]["beats"]
    for beat, duration in zip(beats, [0.5, 0.267, 1.333, 0.5], strict=True):
        beat["duration"] = duration
    added = [("move", "title_1", {"shift": [0, 0.01]}, 0.5)] * 20 + [
        ("set_color", "title_1", {"color": "#E07A5F"}, 0.1),
        ("wait", None, None, 8.2),
        ("set_color", "plot_1", {"color": "#F2CC8F"}, 16.6),
        ("wait", None, None, 0.133),
        ("move", "axes_1", {"shift": [0, -0.5]}, 0.1),
        ("wait", None, None, 9.771),
        ("set_color", "title_1", {"color": "#FFFFFF"}, 2),
    ]
    for index, (action, target, params, duration) in enumerate(added, start=len(beats) + 1):
        added_beat = {
            "id": f"beat_{index}",
            "duration": duration,
            "action": action,
            "targets": [target] if target else [],
        }
        if params is not None:
            added_beat["params"] = params
        beats.append(added_beat)
    project = load_text(json.dumps(raw))
    boundaries = derived_starts([beat.duration for beat in project.scene.beats]) + [total_duration(project)]
    counts = _manim_frame_counts(generate(project), fps)
    assert len(counts) == len(project.scene.beats) == 31
    drawn = 0
    for index, frames in enumerate(counts):
        assert frames >= 1
        drawn += frames
        assert drawn == math.floor(boundaries[index + 1] * fps + 0.5), f"beat index {index} at {fps} fps"


