def _edit_lesson(edit: dict[str, object]) -> tuple[list[bool], str, str]:
    session = Session(load_text(LESSON.read_text(encoding="utf-8")))
    session.mark_rendered("preview")
    before = generate(session.project)
    session.edit(edit)
    return session.dirty_flags("preview"), before, generate(session.project)


def _starts(project: Project) -> list[float]:
    return derived_starts([beat.duration for beat in project.scene.beats])


def _fenced(spec: str, heading: str, language: str) -> str:
    start = spec.index(heading)
    fence = f"```{language}\n"
    begin = spec.index(fence, start) + len(fence)
    end = spec.index("```", begin)
    return spec[begin:end]


def _install_fresh_index(project: Path) -> None:
    project_text = (project / "project.json").read_text(encoding="utf-8")
    loaded = load_text(project_text)
    session = Session(loaded)
    session.mark_rendered("preview")
    cache = project / ".mathimator" / "cache"
    media = cache / "media" / "videos" / "scene" / "480p15"
    media.mkdir(parents=True)
    movie = media / "MainScene.mp4"
    movie.write_bytes(b"movie")
    partial_dir = media / "partial_movie_files" / "MainScene"
    partial_dir.mkdir(parents=True)
    beats: list[IndexBeat] = []
    starts = _starts(loaded)
    for index, beat in enumerate(loaded.scene.beats):
        partial = partial_dir / f"partial-{index}.mp4"
        write_clip(partial)
        beats.append(
            IndexBeat(
                id=beat.id,
                index=index,
                derived_start=starts[index],
                duration=float(beat.duration),
                partial=str(partial),
                last_good=None,
                fresh=True,
            )
        )
    index_path = cache / "preview-index.json"
    rendered_path = cache / "rendered.json"
    index_path.write_text(
        json.dumps(PreviewIndex(output=str(movie), beats=beats).to_dict(), indent=2) + "\n",
        encoding="utf-8",
    )
    rendered_path.write_text(json.dumps(session.rendered_payload(), indent=2) + "\n", encoding="utf-8")


def _ready(client: SupervisorClient) -> None:
    client.send({"cmd": "status", "id": "status"})
    client.wait_for(lambda event: event.get("event") == "ready" and event.get("jobId") == "status", 10)


def _argv_count(log_path: Path) -> int:
    if not log_path.is_file():
        return 0
    return log_path.read_text(encoding="utf-8", errors="replace").count("argv: ")


def _cmdline(pid: int) -> str:
    return process_command_line(pid)


def _fake_pids(supervisor_pid: int, needle: str) -> list[int]:
    """Return descendant pids that are Manim, not the supervisor.

    On Windows the venv interpreter stays as a parent of the real worker, and
    that child's command line includes ``--python`` plus the fake executable.
    Matching the executable path alone would treat the worker as Manim. The
    worker command is ``-m mathimator_worker``; Manim's is ``-m manim``.
    """
    found: list[int] = []
    for pid in _descendant_pids(supervisor_pid):
        command = _cmdline(pid)
        if "-m manim" not in command:
            continue
        if needle != "manim" and needle not in command:
            continue
        found.append(pid)
    return found


def _wait_fake(supervisor_pid: int, fake: Path) -> int:
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        found = _fake_pids(supervisor_pid, str(fake))
        if found:
            return found[0]
        time.sleep(0.02)
    raise AssertionError("fake manim did not start")
