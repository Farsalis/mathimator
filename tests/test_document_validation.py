    raw["scene"]["beats"].append(beat)
    refused = _refused(raw)
    assert (refused.code, refused.field) == ("invalid_document", "scene.beats[8].targets")
    assert str(refused) == f"scene.beats[8] {verb} eq_1, but eq_1 left the screen when it was transformed into eq_2"


