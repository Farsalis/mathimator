def test_a_formula_transformed_away_is_off_screen(
    action: str, targets: list[str], params: dict[str, object] | None, verb: str
) -> None:
    raw = _lesson()
    if "eq_3" in targets:
        third = {"latex": "y", "color": "#FFFFFF", "anchor": "origin"}
        raw["scene"]["objects"].append({"id": "eq_3", "name": "Third", "type": "math_formula", "params": third})
